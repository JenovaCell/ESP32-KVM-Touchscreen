/// Maps macOS virtual key codes to USB HID keyboard usages.
enum HIDMap {
    static let usage: [Int: UInt8] = [
        // letters
        0x00: 4, 0x0B: 5, 0x08: 6, 0x02: 7, 0x0E: 8, 0x03: 9, 0x05: 10, 0x04: 11,
        0x22: 12, 0x26: 13, 0x28: 14, 0x25: 15, 0x2E: 16, 0x2D: 17, 0x1F: 18, 0x23: 19,
        0x0C: 20, 0x0F: 21, 0x01: 22, 0x11: 23, 0x20: 24, 0x09: 25, 0x0D: 26, 0x07: 27,
        0x10: 28, 0x06: 29,
        // number row
        0x12: 30, 0x13: 31, 0x14: 32, 0x15: 33, 0x17: 34, 0x16: 35, 0x1A: 36, 0x1C: 37,
        0x19: 38, 0x1D: 39,
        // punctuation and editing
        0x24: 40, 0x35: 41, 0x33: 42, 0x30: 43, 0x31: 44, 0x1B: 45, 0x18: 46, 0x21: 47,
        0x1E: 48, 0x2A: 49, 0x29: 51, 0x27: 52, 0x32: 53, 0x2B: 54, 0x2F: 55, 0x2C: 56,
