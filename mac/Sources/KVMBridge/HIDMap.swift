    /// Modifier key codes: HID modifier bit and the CGEventFlags mask that tracks it.
    static let modBit: [Int: UInt8] = [
        0x3B: 0x01, 0x38: 0x02, 0x3A: 0x04, 0x37: 0x08,   // left ctrl, shift, option, command
        0x3E: 0x10, 0x3C: 0x20, 0x3D: 0x40, 0x36: 0x80,   // right ctrl, shift, option, command
    ]

    static let modMask: [Int: CGEventFlags] = [
        0x3B: .maskControl, 0x3E: .maskControl,
        0x38: .maskShift, 0x3C: .maskShift,
        0x3A: .maskAlternate, 0x3D: .maskAlternate,
        0x37: .maskCommand, 0x36: .maskCommand,
    ]

    static let capsLock = 0x39
    static let capsLockUsage: UInt8 = 57
}
